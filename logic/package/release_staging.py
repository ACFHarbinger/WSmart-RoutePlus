_TOKEN_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def _docstring_nodes(tree: ast.AST) -> Set[int]:
    """ids of the docstring constants of a module, its classes and functions."""
    ids: Set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.body:
            first = node.body[0]
            if (
                isinstance(first, ast.Expr)
                and isinstance(first.value, ast.Constant)
                and isinstance(first.value.value, str)
            ):
                ids.add(id(first.value))
    return ids


def _reference_counts(tree: ast.Module) -> Dict[str, int]:
    """Identifier uses in a module: names, attributes, keyword names and string-literal tokens.

    Import statements, ``__all__`` entries and docstrings are not uses.
    """
    skip = _docstring_nodes(tree)
    all_node = _all_node(tree)
    if all_node is not None:
        skip.update(id(element) for element in all_node.value.elts)
    counts: Dict[str, int] = {}

    def add(name: str) -> None:
        counts[name] = counts.get(name, 0) + 1

    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            add(node.id)
        elif isinstance(node, ast.Attribute):
            add(node.attr)
        elif isinstance(node, ast.keyword) and node.arg:
            add(node.arg)
        elif isinstance(node, ast.Constant) and isinstance(node.value, str) and id(node) not in skip:
            for token in _TOKEN_RE.findall(node.value):
                add(token)
    return counts


def _definitions(tree: ast.Module) -> List[Tuple[ast.AST, Optional[ast.ClassDef]]]:
    """Top-level functions and classes, and the methods of top-level classes, with their class."""
    found: List[Tuple[ast.AST, Optional[ast.ClassDef]]] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            found.append((node, None))
        if isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    found.append((item, node))
    return found


def _base_names(node: ast.ClassDef) -> List[str]:
    names = []
    for base in node.bases:
        target = base.value if isinstance(base, ast.Subscript) else base
        if isinstance(target, ast.Name):
            names.append(target.id)
        elif isinstance(target, ast.Attribute):
            names.append(target.attr)
    return names


def _external_rooted(classes: Dict[str, List[ast.ClassDef]]) -> Set[str]:
    """Class names that inherit (transitively) from a class defined outside the staged tree.

    The framework calls their methods (Lightning hooks, ``forward``, dataset protocols), so
    none of their methods is pruned. ``object`` and ``ABC`` do not count.
    """
    rooted: Set[str] = set()
    changed = True
    while changed:
        changed = False
        for name, nodes in classes.items():
            if name in rooted:
                continue
            for node in nodes:
                for base in _base_names(node):
                    if base in ("object", "ABC", "Protocol", "Generic", "NamedTuple", "Exception"):
                        continue
                    if base not in classes or base in rooted:
                        rooted.add(name)
                        changed = True
                        break
                if name in rooted:
                    break
    return rooted


_PURE_CALLS = frozenset({"list", "dict", "tuple", "set", "frozenset", "sorted", "len", "str", "int", "float", "bool"})
_PURE_METHODS = frozenset({"keys", "values", "items", "copy", "upper", "lower"})


def _is_pure(value: ast.AST) -> bool:
    """A value whose only calls are pure builtins: deleting its assignment has no side effect."""
    for node in ast.walk(value):
        if isinstance(node, (ast.Await, ast.Yield, ast.YieldFrom)):
            return False
        if isinstance(node, ast.Call):
            pure_builtin = isinstance(node.func, ast.Name) and node.func.id in _PURE_CALLS
            pure_method = isinstance(node.func, ast.Attribute) and node.func.attr in _PURE_METHODS
            if not (pure_builtin or pure_method):
                return False
    return True


def _prunable(tree: ast.Module) -> List[Tuple[ast.AST, Optional[ast.ClassDef], str]]:
    """Definitions and pure constant assignments a pass may delete, with their class and name."""
    found: List[Tuple[ast.AST, Optional[ast.ClassDef], str]] = [
        (node, owner, node.name)  # type: ignore[attr-defined]
        for node, owner in _definitions(tree)
        if not node.decorator_list  # type: ignore[attr-defined]
    ]
    for node in tree.body:
        targets = (
            node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        )
        value = getattr(node, "value", None)
        if len(targets) == 1 and isinstance(targets[0], ast.Name) and value is not None and _is_pure(value):
            found.append((node, None, targets[0].id))
    return found


def _dead_spans(
    path: Path, tree: ast.Module, totals: Dict[str, int], rooted: Set[str], keep_names: Set[str], out: Path
) -> Tuple[List[Tuple[int, int, str]], Set[int]]:
    """Line spans of a module's dead definitions, and the lines a ``pass`` must replace."""
    spans: List[Tuple[int, int, str]] = []
    owners: Dict[int, ast.ClassDef] = {}
    for node, owner, name in _prunable(tree):
        if name.startswith("__") or name in keep_names or name == "logger":
            continue
        if owner is not None and owner.name in rooted:
            continue
        inside = _reference_counts(ast.Module(body=[node], type_ignores=[])).get(name, 0)  # type: ignore[list-item]
        if totals.get(name, 0) - inside > 0:
            continue
        spans.append((node.lineno, node.end_lineno or node.lineno, f"{path.relative_to(out)}: {name}"))
        if owner is not None:
            owners[id(owner)] = owner
    # A method inside a class that is itself deleted goes with the class.
    spans = [span for span in spans if not any(o[0] < span[0] and span[1] <= o[1] for o in spans if o != span)]
    replace_with_pass: Set[int] = set()
    for owner in owners.values():
        removed = [span for span in spans if owner.lineno < span[0] <= (owner.end_lineno or 0)]
        if removed and len(removed) == len(owner.body):
            replace_with_pass.add(min(span[0] for span in removed))
    return spans, replace_with_pass


def _delete_spans(path: Path, spans: List[Tuple[int, int, str]], replace_with_pass: Set[int]) -> List[str]:
    lines = path.read_text().splitlines(keepends=True)
    notes = []
    for start, end, note in sorted(spans, reverse=True):
        indent = lines[start - 1][: len(lines[start - 1]) - len(lines[start - 1].lstrip())]
        lines[start - 1 : end] = [indent + "pass\n"] if start in replace_with_pass else []
        notes.append(f"pruned unreferenced {note}")
    path.write_text("".join(lines))
    drop_unbound_exports(path)
    return notes


def _reference_totals(trees: Dict[Path, ast.Module], base: Dict[str, int]) -> Tuple[Dict[str, int], Set[str]]:
    """Name uses across the trees (plus ``base``), and the classes rooted in an external base.

    The method names of rooted classes and every abstract method name also count as used: a
    framework (Lightning, TorchRL, ``abc``) calls them, also when a mixin implements them.
    """
    totals = dict(base)
    classes: Dict[str, List[ast.ClassDef]] = {}
    for tree in trees.values():
        for name, count in _reference_counts(tree).items():
            totals[name] = totals.get(name, 0) + count
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                classes.setdefault(node.name, []).append(node)
    rooted = _external_rooted(classes)
    # The in-tree bases (mixins) of a rooted class implement methods the framework calls too.
    facing = set(rooted)
    stack = list(rooted)
    while stack:
        for node in classes.get(stack.pop(), []):
            for base in _base_names(node):
                if base in classes and base not in facing:
                    facing.add(base)
                    stack.append(base)
    framework_called: Set[str] = set()
    for name, nodes in classes.items():
        for node in nodes:
            for item in node.body:
                if not isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                abstract = any(
                    (isinstance(d, ast.Name) and d.id == "abstractmethod")
                    or (isinstance(d, ast.Attribute) and d.attr == "abstractmethod")
                    for d in item.decorator_list
                )
                if abstract or name in facing:
                    framework_called.add(item.name)
    for method in framework_called:
        totals[method] = totals.get(method, 0) + 2  # survives the "inside its own body" discount
    return totals, rooted


def _imported_modules(sources: List[Path], out: Path) -> Set[str]:
    """Every ``logic`` module some source imports (as a module or as ``from <pkg> import <mod>``)."""
    found: Set[str] = set()
    for path in sources:
        tree = ast.parse(path.read_text())
        for node in ast.walk(tree):
            targets = _import_targets(node, path, out) if isinstance(node, (ast.Import, ast.ImportFrom)) else None
            found.update(target for target in targets or () if target.startswith("logic"))
    return found


def _delete_empty_modules(sources: List[Path], out: Path) -> List[str]:
    """Delete non-package modules left with only imports and a docstring that nothing imports."""
    imported = _imported_modules(sources, out)
    notes = []
    for path in list(sources):
        if path.name == "__init__.py" or path.name == "__main__.py":
            continue
        tree = ast.parse(path.read_text())
        body = [n for n in tree.body if not isinstance(n, (ast.Import, ast.ImportFrom, ast.Expr))]
        if body or file_to_module(path, out) in imported:
            continue
        path.unlink()
        sources.remove(path)
        notes.append(f"deleted emptied module {path.relative_to(out)}")
    return notes


def prune_unreferenced(out: Path, keep_names: Set[str], max_rounds: int = 30) -> List[str]:
    """Delete the definitions and pure constants of the staged tree that nothing references.

    A definition is dead when its name occurs nowhere in the staged code outside its own body
    (identifiers, attributes, keyword names, string-literal tokens) nor in the staged YAML
    configs. Tests do not count. Dunder names, methods of classes rooted in an external base,
    decorated definitions, assignments with calls and ``keep_names`` are kept. Repeats until
    nothing changes, removes the imports of deleted names (deepest package first, until stable)
    and deletes the modules left empty. Returns one note per deletion.
    """
    sources = [p for p in sorted((out / "logic").rglob("*.py")) if "test" not in p.relative_to(out).parts[:2]]
    if (out / "__main__.py").is_file():
        sources.append(out / "__main__.py")
    yaml_counts: Dict[str, int] = {}
    for config in (out / "logic").rglob("*.yaml"):
        for token in _TOKEN_RE.findall(config.read_text()):
            yaml_counts[token] = yaml_counts.get(token, 0) + 1
    notes: List[str] = []
    for _ in range(max_rounds):
        trees = {path: ast.parse(path.read_text()) for path in sources}
        totals, rooted = _reference_totals(trees, yaml_counts)
        changed = False
        for path, tree in trees.items():
            spans, replace_with_pass = _dead_spans(path, tree, totals, rooted, keep_names, out)
            if spans:
                notes += _delete_spans(path, spans, replace_with_pass)
                changed = True
        staged_modules = {file_to_module(p, out) for p in (out / "logic").rglob("*.py")}
        for path in sorted(sources, key=lambda p: (-len(p.parts), str(p))):
            dropped = drop_pruned_init_imports(path, staged_modules, out)
            notes += dropped
            changed = changed or bool(dropped)
        deleted = _delete_empty_modules(sources, out)
        notes += deleted
        if not (changed or deleted):
            break
    return notes
