def run_ms_bpc_sp(  # noqa: C901
    problem: SubProblem,
    cfg: Optional[Union[MSBPCSPConfig, Dict[str, Any]]] = None,
    *,
    _presel_retry: bool = False,
    _keep_all_nodes: bool = False,
) -> SolveResult:
    """Solve Waste-Collecting CVRP using exact Branch-and-Price-and-Cut.

    This engine implements the Barnhart et al. (1998, OR 46(3):316-329) BPC framework with
    configurable algorithmic strategies:

    1. Initial Column Generation via greedy heuristics
    2. Branch-and-Bound tree with pluggable branching strategies
    3. Column Generation at every B&B node (following exact BPC sequencing)
    4. Exact Pricing via RCSPP
    5. Modular Valid Inequalities (RCC)
    6. Configurable search strategy (Depth-First search is preferred for basis reuse)

    Algorithm Overview:
    - Initialize B&B tree with root node and selected strategy
    - While tree is not empty:
        - Select next node using configured search strategy
        - Apply branching constraints to master and pricing
        - Run Column Generation + Cutting Plane loop (corrected sequencing)
        - If LP is integer: update incumbent
        - If LP is fractional: branch using configured branching rule
        - Prune by bound

    Args:
        problem: Routing sub-problem (distances, wastes, capacity,
            revenue, cost unit, mandatory nodes, fleet limit, environment).
        cfg: Configuration. A
            raw dict is coerced leniently into MSBPCSPConfig (WP-04 pattern).
        _presel_retry: Internal — set on the empty-result re-solve pass
            (relaxed knapsack budget). Not part of the public contract.
        _keep_all_nodes: Internal — set on the relaxation re-solve pass
            (no node pre-selection). Not part of the public contract.

    Returns:
        SolveResult: NamedTuple(routes, profit, cost) — routes are
        customer-node lists (depot excluded), profit is the net objective
        (revenue − travel cost), cost is C × total route distance.

    Example:
        >>> from logic.src.policies.routing.base.sub_problem import build_subproblem
        >>> from logic.src.policies.routing.exact_and_decomposition_solvers.multi_stage_branch_and_price_and_cut_with_set_partition.ms_bpc_sp_engine import run_ms_bpc_sp
        >>> dist_matrix = np.array([[0, 10], [10, 0]])
        >>> wastes = {1: 5.0}
        >>> problem = build_subproblem(dist_matrix, wastes, capacity=10, revenue=1, cost_unit=1)
        >>> result = run_ms_bpc_sp(problem)  # SolveResult(routes, profit, cost)
    """
    start_time = time.perf_counter()

    # Standardize cfg to MSBPCSPConfig (P-10: the typed config is the only parameter layer)
    if cfg is None:
        cfg = MSBPCSPConfig()
    elif isinstance(cfg, dict):
        cfg = _structured_load(MSBPCSPConfig, _unwrap_engine_section(cfg))

    # Unpack the SubProblem value object (P-30 contract).
    dist_matrix = problem.dist_matrix
    wastes = problem.wastes
    capacity = problem.capacity
    R = problem.revenue
    C = problem.cost_unit
    mandatory_indices = set(problem.mandatory_nodes)
    # Explicit int conversion and positive check. None and 0 both map to
    # unlimited fleet. False is rejected at the int() call (TypeError surfaced
    # to the caller) rather than silently treated as unlimited.
    n_vehicles = problem.n_vehicles
    vehicle_limit = None if n_vehicles is None else int(n_vehicles) if int(n_vehicles) > 0 else None
    env = problem.env
    recorder = problem.recorder
    n_nodes = len(dist_matrix) - 1
    m_set = mandatory_indices

    params = cfg

    # Configuration
    # Extract parameters from the typed config
    max_bb_nodes = params.max_bb_nodes
    time_limit = params.time_limit
    cutting_planes_name = params.cutting_planes
    branching_strategy_name = params.branching_strategy

    # Numerical Safety Warning
    if params.rc_tolerance > params.optimality_gap:
        warnings.warn(
            f"Optimality Risk: rc_tolerance ({params.rc_tolerance}) is coarser than "
            f"optimality_gap ({params.optimality_gap}). BPC may terminate prematurely "
            f"with a sub-optimal solution.",
            stacklevel=2,
        )

    # 1. Initialize Master Problem
    # Pre-select profitable nodes via knapsack to reduce RCSPP instance size.
    # BPC then runs only on this reduced node set. On the empty-result retry
    # pass the budget is relaxed (no fleet scaling) because the capacity budget
    # assumes per-node additive value, while route-cost sharing makes value
    # non-additive: a node dropped by the budget can be half of the only
    # profitable pairing, and the BPC never sees it.
    _knapsack_budget = min(10.0, time_limit * 0.05) if time_limit > 0 else 10.0
    if _keep_all_nodes or params.exact_mode or n_nodes <= 12:
        # Exact mode, small instances, or relaxation pass: keep all nodes to prevent lossy reduction.
        selected_nodes = set(range(1, n_nodes + 1)) | set(m_set)
    else:
        selected_nodes = _select_nodes_knapsack(
            dist_matrix=dist_matrix,
            wastes=wastes,
            capacity=capacity,
            R=R,
            C=C,
            mandatory=m_set,
            n_nodes=n_nodes,
            time_limit=_knapsack_budget,
            env=env,
            vehicle_limit=None if _presel_retry else vehicle_limit,
        )

    k_nodes, local_to_orig, red_dist, red_wastes, red_mandatory = _remap_instance(
        dist_matrix, wastes, m_set, selected_nodes
    )

    master = VRPPMasterProblem(
        n_nodes=k_nodes,
        mandatory_nodes=red_mandatory,
        cost_matrix=red_dist,
        wastes=red_wastes,
        capacity=capacity,
        revenue_per_kg=R,
        cost_per_km=C,
        vehicle_limit=vehicle_limit,
    )

    # Task 3/6: Harden Ryan-Foster Exactness
    if branching_strategy_name == "ryan_foster":
        master.strict_set_partitioning = True
        logger.info("Enforcing strict Set Partitioning (SP) for Ryan-Foster branching.")

    pricing_solver = RCSPPSolver(
        k_nodes,
        red_dist,
        red_wastes,
        capacity,
        R,
        C,
        use_ng_routes=params.use_ng_routes,
        ng_neighborhood_size=min(params.ng_neighborhood_size, k_nodes - 1),
        timeout=params.rcspp_timeout,
        max_labels=params.rcspp_max_labels,
    )

    # 2. Initial Columns — greedy-insertion warm start on the reduced instance
    mandatory_list = sorted(red_mandatory)
    optional_local = [n for n in range(1, k_nodes + 1) if n not in red_mandatory]
    initial_routes_nodes, initial_columns = greedy_warm_start_columns(
        pricing_solver,
        mandatory_list,
        optional_local,
        red_dist,
        red_wastes,
        capacity,
        R,
        C,
        enabled=params.greedy_warm_start,
        profit_aware=params.profit_aware_operators,
    )

    master.build_model(initial_columns)
    master.column_deletion_enabled = True

    # 2.1 Initialize 2-Phase Method
    # Start in Phase 1 (Feasibility) if there are mandatory nodes to cover.
    if len(red_mandatory) > 0:
        master.set_phase(1)
    else:
        master.set_phase(2)

    bb_tree, cut_engine = _build_tree_and_cuts(
        k_nodes, red_dist, red_wastes, capacity, R, C, red_mandatory, params, cutting_planes_name
    )
    logger.info(
        f"BPC Solver started: instance size {k_nodes} nodes "
        f"(reduced from {n_nodes} via knapsack pre-selection), "
        f"max BB nodes: {max_bb_nodes}"
    )

    # 6. Shared B&B walk (P-33 / RQ-kimi-2). Knapsack + remap stay above;
    # Phase 3/5 + empty-result retries stay below. MS certificates stay on
    # MSBPCSPConfig defaults and these flags (not BPCConfig).
    nodes_explored = search_bpc_tree(
        master=master,
        pricing_solver=pricing_solver,
        cut_engine=cut_engine,
        bb_tree=bb_tree,
        cfg=params,
        branching_strategy_name=branching_strategy_name,
        time_limit=time_limit,
        start_time=start_time,
        red_dist=red_dist,
        red_wastes=red_wastes,
        capacity=capacity,
        R=R,
        C=C,
        m_set=m_set,
        env=env,
        recorder=recorder,
        k_nodes=k_nodes,
        options=BPCSearchOptions(
            strict_certification=True,
            require_elementary=True,
            incomplete_node_ip=True,
            lr_requires_vehicle_limit=False,
            scale_lr_by_vehicle_limit=False,
        ),
    )

    # 6. Extract best integer solution — always proceed to Phase 3 regardless
    bpc_routes_orig, bpc_cost = _best_bpc_solution(bb_tree, master, pricing_solver, initial_routes_nodes, local_to_orig)

    # ── Phase 3: Regret-2 greedy over ALL 100 nodes ───────────────────────
    # Starting from BPC routes, greedily insert every profitable unvisited
    # node. Can open new routes when existing ones are full. Near-overflow
    # bins (fill >= MAX_CAPACITY_PERCENT) are prioritised via regret boost.
    bpc_elapsed = time.perf_counter() - start_time
    remaining_budget = (time_limit if time_limit > 0 else 60.0) - bpc_elapsed
    phase3_budget = max(0.0, remaining_budget - 15.0)  # reserve 15s for phases 4+5

    final_routes: List[List[int]] = [list(r) for r in bpc_routes_orig]
    final_cost = bpc_cost
    visited_orig: Set[int] = {n for route in final_routes for n in route}

    logger.info(
        f"[Phase 3] Starting: {len(final_routes)} BPC routes, "
        f"{len(visited_orig)} visited nodes, phase3_budget={phase3_budget:.1f}s, "
        f"n_nodes={n_nodes}, m_set_size={len(m_set)}."
    )
    if phase3_budget > 0.5:
        final_routes, final_cost = _regret2_insertion(
            final_routes,
            final_cost,
            visited_orig,
            phase3_budget,
            n_nodes,
            m_set,
            wastes,
            capacity,
            R,
            C,
            dist_matrix,
            vehicle_limit,
        )
    # ── End Phase 3 ────────────────────────────────────────────────────────

    # ── Phase 5: Set Partitioning over BPC pool + Phase 3 routes ──────────
    phase5_elapsed = time.perf_counter() - start_time
    phase5_budget = max(0.0, (time_limit if time_limit > 0 else 60.0) - phase5_elapsed)

    if phase5_budget > 2.0:
        final_routes, final_cost = _set_partition_merge(
            master.routes,
            local_to_orig,
            final_routes,
            final_cost,
            phase5_budget,
            n_nodes,
            m_set,
            wastes,
            R,
            C,
            dist_matrix,
            vehicle_limit,
        )
    # ── End Phase 5 ────────────────────────────────────────────────────────

    fallback_result = _empty_result_fallback(
        run_ms_bpc_sp,
        problem,
        params,
        start_time,
        time_limit,
        final_routes,
        k_nodes,
        n_nodes,
        vehicle_limit,
        m_set,
        dist_matrix,
        C,
        _presel_retry,
        _keep_all_nodes,
    )
    if fallback_result is not None:
        return fallback_result

    if recorder:
        recorder.record(
            engine="exact_bpc",
            iterations=nodes_explored,
            obj_val=final_cost,
            n_routes=len(final_routes),
        )

    return SolveResult(
        routes=final_routes,
        profit=final_cost,
        cost=_total_travel_cost(final_routes, dist_matrix, C),
    )
