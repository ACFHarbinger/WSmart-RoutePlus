def run_bpc(  # noqa: C901
    problem: SubProblem,
    cfg: Optional[Union[BPCConfig, Dict[str, Any]]] = None,
) -> SolveResult:
    """Solve Waste-Collecting CVRP using exact Branch-and-Price-and-Cut.

    This engine implements the Barnhart et al. (1998, OR 46(3):316-329) BPC framework with
    configurable algorithmic strategies:

    1. Initial Column Generation via greedy heuristics
    2. Branch-and-Bound tree with pluggable branching strategies
    3. Column Generation at every B&B node (following exact BPC sequencing)
    4. Exact Pricing via RCSPP
    5. Modular Valid Inequalities (RCC)
    6. Configurable search strategy (Depth-First search is preferred for basis reuse)

    Algorithm Overview:
    - Initialize B&B tree with root node and selected strategy
    - While tree is not empty:
        - Select next node using configured search strategy
        - Apply branching constraints to master and pricing
        - Run Column Generation + Cutting Plane loop (corrected sequencing)
        - If LP is integer: update incumbent
        - If LP is fractional: branch using configured branching rule
        - Prune by bound

    Args:
        problem: Routing sub-problem (distances, wastes, capacity,
            revenue, cost unit, mandatory nodes, fleet limit, environment).
        cfg: Configuration. A raw
            dict is coerced leniently into BPCConfig (WP-04 pattern).

    Returns:
        SolveResult: NamedTuple(routes, profit, cost) — routes are
        customer-node lists (depot excluded), profit is the net objective
        (revenue − travel cost), cost is C × total route distance.

    Example:
        >>> from logic.src.policies.routing.base.sub_problem import build_subproblem
        >>> from logic.src.policies.routing.exact_and_decomposition_solvers.branch_and_price_and_cut.bpc_engine import run_bpc
        >>> dist_matrix = np.array([[0, 10], [10, 0]])
        >>> wastes = {1: 5.0}
        >>> problem = build_subproblem(dist_matrix, wastes, capacity=10, revenue=1, cost_unit=1)
        >>> result = run_bpc(problem)  # SolveResult(routes, profit, cost)
    """
    from logic.src.pipeline.simulations.reporting import (
        note_solver_incumbent,
        note_solver_status,
        reset_solver_certificate,
    )

    start_time = time.perf_counter()

    # Standardize cfg to BPCConfig (P-10: the typed config is the only parameter layer)
    if cfg is None:
        cfg = BPCConfig()
    elif isinstance(cfg, dict):
        cfg = _structured_load(BPCConfig, _unwrap_engine_section(cfg))
    cfg = cast(BPCConfig, cfg)

    # Unpack the SubProblem value object (P-30 contract).
    dist_matrix = problem.dist_matrix
    wastes = problem.wastes
    capacity = problem.capacity
    R = problem.revenue
    C = problem.cost_unit
    mandatory_indices = set(problem.mandatory_nodes)
    # Explicit int conversion and positive check. None and 0 both map to
    # unlimited fleet. False is rejected at the int() call (TypeError surfaced
    # to the caller) rather than silently treated as unlimited.
    n_vehicles = problem.n_vehicles
    vehicle_limit = None if n_vehicles is None else int(n_vehicles) if int(n_vehicles) > 0 else None
    from logic.src.utils.routing.problem_fingerprint import problem_fingerprint

    reset_solver_certificate(problem_fingerprint(dist_matrix, wastes, capacity, R, C, mandatory_indices, vehicle_limit))
    env = problem.env
    recorder = problem.recorder
    n_nodes = len(dist_matrix) - 1
    m_set = mandatory_indices

    # Configuration
    # Extract parameters from the typed config
    max_bb_nodes = cfg.max_bb_nodes
    time_limit = cfg.time_limit
    branching_strategy_name = cfg.branching_strategy

    # Numerical Safety Warning
    if cfg.rc_tolerance > cfg.optimality_gap:
        warnings.warn(
            f"Optimality Risk: rc_tolerance ({cfg.rc_tolerance}) is coarser than "
            f"optimality_gap ({cfg.optimality_gap}). BPC may terminate prematurely "
            f"with a sub-optimal solution.",
            stacklevel=2,
        )

    # 1. Initialize Master Problem over the FULL instance.
    # No node pre-selection — BPC prices over all n_nodes simultaneously.
    # The RCSPP subproblem handles both node selection and routing via reduced costs.
    k_nodes = n_nodes
    red_dist = dist_matrix
    red_wastes = wastes
    red_mandatory = m_set

    master = VRPPMasterProblem(  # type: ignore[abstract]  # abstract attrs come from master mixins, not this call site
        n_nodes=k_nodes,
        mandatory_nodes=red_mandatory,
        cost_matrix=red_dist,
        wastes=red_wastes,
        capacity=capacity,
        revenue_per_kg=R,
        cost_per_km=C,
        vehicle_limit=vehicle_limit,
    )

    # Task 3/6: Harden Ryan-Foster Exactness
    if branching_strategy_name == "ryan_foster":
        master.strict_set_partitioning = True
        logger.info("Enforcing strict Set Partitioning (SP) for Ryan-Foster branching.")

    pricing_solver = make_pricing_solver(cfg, k_nodes, red_dist, red_wastes, capacity, R, C)

    # 2. Initial Columns — greedy-insertion warm start on the reduced instance
    mandatory_list = sorted(red_mandatory)
    optional_local = [n for n in range(1, k_nodes + 1) if n not in red_mandatory]
    initial_routes_nodes, initial_columns = greedy_warm_start_columns(
        pricing_solver,
        mandatory_list,
        optional_local,
        red_dist,
        red_wastes,
        capacity,
        R,
        C,
        enabled=cfg.greedy_warm_start,
        profit_aware=cfg.profit_aware_operators,
    )

    master.build_model(initial_columns)
    priced = cast(Any, pricing_solver)
    if hasattr(priced, "is_known_column"):
        priced.is_known_column = lambda sig: sig in master._route_signatures
    master.column_deletion_enabled = True

    # 2.1 Initialize 2-Phase Method
    # Start in Phase 1 (Feasibility) if there are mandatory nodes to cover.
    if len(red_mandatory) > 0:
        master.set_phase(1)
    else:
        master.set_phase(2)

    trace, stage_id = begin_solver(problem, "bpc")
    attach_master(master, trace, stage_id)
    if trace is not None:
        emit_phase(master, master.phase, "farkas" if master.phase == 1 else "ordinary")

    # 3. Initialize pricing and separation — use REDUCED instance throughout
    # pricing_solver is already initialized above on red_dist/red_wastes — reuse it.
    n_total_nodes = k_nodes + 1  # VRPPModel counts total nodes including depot (index 0)
    v_model = VRPPModel(
        n_nodes=n_total_nodes,
        cost_matrix=red_dist,
        wastes=red_wastes,
        capacity=capacity,
        revenue_per_kg=R,
        cost_per_km=C,
        mandatory_nodes=red_mandatory,
    )
    sep_engine = SeparationEngine(
        model=v_model,
        enable_heuristic_rcc_separation=cfg.enable_heuristic_rcc_separation,
        enable_comb_cuts=cfg.enable_comb_cuts,
    )

    # 4. Initialize Branch-and-Bound Tree with search strategy
    bb_tree = BranchAndBoundTree(v_model=v_model, params=cfg)

    # 5. Initialize cutting engine (the CMPTP pricer keeps only the families it can price)
    cut_engine = make_cut_engine(cfg, v_model, sep_engine, red_dist)
    logger.info(f"BPC Solver started: full instance, {k_nodes} nodes, max BB nodes: {max_bb_nodes}")

    # 6. Shared B&B walk (P-33). Setup above stays BPC-specific (full instance,
    # Rank-1 supplemental cuts). Extraction below stays BPC-specific.
    try:
        nodes_explored = search_bpc_tree(
            master=master,
            pricing_solver=pricing_solver,
            cut_engine=cut_engine,
            bb_tree=bb_tree,
            cfg=cfg,
            branching_strategy_name=branching_strategy_name,
            time_limit=time_limit,
            start_time=start_time,
            red_dist=red_dist,
            red_wastes=red_wastes,
            capacity=capacity,
            R=R,
            C=C,
            m_set=m_set,
            env=env,
            recorder=recorder,
            k_nodes=k_nodes,
            options=BPCSearchOptions(incomplete_node_ip=cfg.salvage_incomplete_node),
        )
    finally:
        detach_master(master)

    pricing_stats = getattr(priced, "stats", None)
    if pricing_stats:
        logger.info(f"[BPC] CMPTP pricing stats: {dict(pricing_stats)}")

    # 6. Extract best integer solution
    if bb_tree.best_integer_node is None and not cfg.allow_fallback:
        # Strict evaluation: no integer node within the limit means no plan, not a substitute plan.
        note_solver_status("bpc:no_incumbent")
        note_solver_incumbent(0.0)
        close_solver(trace, stage_id, [], 0.0)
        return SolveResult(routes=[], profit=0.0, cost=0.0)
    if bb_tree.best_integer_node is None:
        # No integer node was reached (e.g. the time limit hit during the root).
        # Return the best plan available: the mandatory-only greedy routes, or the
        # restricted master solved as an IP over every column generated so far,
        # whichever is more profitable. (The greedy list alone is empty whenever no
        # bin is mandatory, which reported a 0 km / 0 kg day.)
        fallback_routes = [list(r) for r in initial_routes_nodes]
        fallback_profit = sum(pricing_solver._compute_route_details(r).profit for r in fallback_routes)
        source = "greedy"
        try:
            _apply_branching_to_master(master, [], branching_strategy_name)
            cast(Any, master.model).Params.TimeLimit = max(1.0, min(10.0, 0.1 * time_limit if time_limit > 0 else 10.0))
            ip_obj, ip_routes = master.solve_ip()
            if ip_routes and ip_obj > fallback_profit + 1e-9:
                fallback_routes, fallback_profit = [list(r.nodes) for r in ip_routes], float(ip_obj)
                source = "rmp_ip"
        except Exception as exc:  # the greedy plan is still valid
            logger.warning(f"Restricted-master IP fallback failed: {exc}")
        # The day log records the fallback, so its frequency is countable.
        note_solver_status(f"bpc:fallback_{source}")
        note_solver_incumbent(fallback_profit)
        close_solver(trace, stage_id, fallback_routes, fallback_profit)
        return SolveResult(
            routes=fallback_routes,
            profit=fallback_profit,
            cost=_total_travel_cost(fallback_routes, dist_matrix, C),
        )

    # Reconstruct solution from best node
    best_node = bb_tree.best_integer_node
    best_routes_objects = [
        master.routes[idx]
        for idx, val in best_node.route_values.items()  # type: ignore[union-attr]
        if val > 0.5
    ]

    final_routes = [r.nodes for r in best_routes_objects]
    final_cost = sum(r.profit for r in best_routes_objects)

    if recorder:
        recorder.record(
            engine="exact_bpc",
            iterations=nodes_explored,
            obj_val=bb_tree.best_integer_solution,
            n_routes=len(final_routes),
        )

    note_solver_incumbent(final_cost)
    close_solver(trace, stage_id, final_routes, final_cost)
    return SolveResult(
        routes=final_routes,
        profit=final_cost,
        cost=_total_travel_cost(final_routes, dist_matrix, C),
    )
