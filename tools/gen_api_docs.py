"""Generate the API reference from the source docstrings (WP-13, Q-22).

The hand-written module docs under ``docs/modules/`` drift (the packing/routing
rename had to edit 28 documentation files by hand). Per the Q-22 ruling this
generator produces the API reference from the actual tree: one markdown page
per package under ``logic/src/`` (plus the CLI), listing each public module
with its docstring summary and its public class/function inventory.

Run from the repository root::

    python tools/gen_api_docs.py [--out docs/api]

The output is deterministic (sorted), so a CI step can diff it against the
committed copy to detect drift.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path
from typing import List, Optional

REPO = Path(__file__).resolve().parents[1]
LOGIC_SRC = REPO / "logic" / "src"
PACKAGES = sorted(p.name for p in LOGIC_SRC.iterdir() if p.is_dir() and (p / "__init__.py").exists()) + ["controllers"]
SKIP_DIRS = {"__pycache__"}


def is_public(name: str) -> bool:
    return not name.startswith("_")


def summary_of(docstring: Optional[str]) -> str:
    if not docstring:
        return ""
    for line in docstring.strip().splitlines():
        stripped = line.strip()
        if stripped:
            return stripped
    return ""


def module_page(module_path: Path, repo_relative: str) -> str:
    """One markdown section for a module: summary + public inventory."""
    try:
        tree = ast.parse(module_path.read_text())
    except SyntaxError:
        return f"### `{repo_relative}`\n\n(unparsable)\n"
    lines = [f"### `{repo_relative}`", ""]
    summary = summary_of(ast.get_docstring(tree))
    if summary:
        lines += [summary, ""]
    inventory: List[str] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and is_public(node.name):
            doc = summary_of(ast.get_docstring(node)) or "—"
            inventory.append(f"- **class `{node.name}`** — {doc}")
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and is_public(node.name):
            doc = summary_of(ast.get_docstring(node)) or "—"
            inventory.append(f"- `{node.name}()` — {doc}")
    if inventory:
        lines += inventory + [""]
    return "\n".join(lines)


def package_page(package: str) -> str:
    """The markdown page for one package."""
    root = REPO / "logic" / package if package == "controllers" else LOGIC_SRC / package
    lines = [
        "<!-- Generated by tools/gen_api_docs.py (Q-22). Do not edit; regenerate. -->",
        f"# API reference — `logic.{'controllers' if package == 'controllers' else 'src.' + package}`",
        "",
    ]
    modules = sorted(root.rglob("*.py"))
    modules = [m for m in modules if not any(part in SKIP_DIRS for part in m.parts)]
    if not modules:
        lines += ["(no modules)", ""]
        return "\n".join(lines)
    lines.append(f"{len(modules)} modules.")
    lines.append("")
    for module in modules:
        rel = module.relative_to(REPO)
        repo_relative = str(rel.with_suffix("")).replace("/", ".")
        lines.append(module_page(module, repo_relative))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="docs/api", help="output directory")
    args = parser.parse_args()
    out = REPO / args.out
    out.mkdir(parents=True, exist_ok=True)
    index = [
        "<!-- Generated by tools/gen_api_docs.py (Q-22). Do not edit; regenerate. -->",
        "# WSmart-Route API reference",
        "",
        "Generated from the source docstrings; the hand-written guides under",
        "`docs/modules/` are superseded by this reference and kept for narrative",
        "only. `docs/moon/` stays internal.",
        "",
        "| Package | Page |",
        "|---|---|",
    ]
    for package in PACKAGES:
        page = package_page(package)
        slug = f"{package}.md"
        (out / slug).write_text(page)
        index.append(
            f"| `logic.{'controllers' if package == 'controllers' else 'src.' + package}` | [{slug}]({slug}) |"
        )
    (out / "README.md").write_text("\n".join(index) + "\n")
    print(f"generated {len(PACKAGES)} package pages under {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
