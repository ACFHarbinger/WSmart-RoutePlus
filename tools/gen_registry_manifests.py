"""Scan @register decorators and write lazy registry manifests.

Run from the repository root. This is a one-shot Q-8b migration helper.
"""

from __future__ import annotations

import ast
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "logic" / "src"


def module_path(py_file: Path) -> str:
    rel = py_file.relative_to(SRC).with_suffix("")
    return "logic.src." + ".".join(rel.parts)


def class_after(tree: ast.AST, lineno: int) -> Optional[str]:
    classes = [node for node in ast.walk(tree) if isinstance(node, ast.ClassDef) and node.lineno >= lineno]
    if not classes:
        return None
    return min(classes, key=lambda node: node.lineno).name


def decorator_name(node: ast.AST) -> str:
    if isinstance(node, ast.Call):
        return ast.unparse(node.func)
    return ast.unparse(node)


def string_args(call: ast.Call) -> List[str]:
    values = []
    for arg in call.args:
        if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
            values.append(arg.value)
    return values


def scan(directory: Path, register_suffix: str) -> Dict[str, Tuple[str, str]]:
    """Map registry key → (module:Class, file)."""
    entries: Dict[str, Tuple[str, str]] = {}
    for path in sorted(directory.rglob("*.py")):
        if path.name.startswith("_"):
            continue
        text = path.read_text()
        if register_suffix not in text:
            continue
        tree = ast.parse(text)
        for node in ast.walk(tree):
            if not isinstance(node, ast.ClassDef):
                continue
            for dec in node.decorator_list:
                if not isinstance(dec, ast.Call):
                    continue
                func = decorator_name(dec)
                if not func.endswith(register_suffix):
                    continue
                for key in string_args(dec):
                    entries[key] = (f"{module_path(path)}:{node.name}", str(path))
    return entries


def write_manifest(path: Path, registry_import: str, registry_name: str, entries: Dict[str, Tuple[str, str]], extra: str = "") -> None:
    lines = [
        '"""Lazy registry entries generated by tools/gen_registry_manifests.py."""',
        "",
        "from __future__ import annotations",
        "",
        f"from {registry_import} import {registry_name}",
        "",
        "ENTRIES = {",
    ]
    for key in sorted(entries):
        target, _ = entries[key]
        lines.append(f'    {key!r}: {target!r},')
    lines.append("}")
    lines.append("")
    lines.append("def load() -> None:")
    lines.append("    for name, target in ENTRIES.items():")
    lines.append(f"        {registry_name}.declare(name, target)")
    if extra:
        lines.append(extra)
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path} ({len(entries)} entries)")


def main() -> None:
    packing = scan(SRC / "policies" / "packing", "PackingRegistry.register")
    write_manifest(
        SRC / "policies" / "packing" / "_manifest.py",
        "logic.src.utils.registry",
        "PACKING",
        packing,
        extra=(
            "    PACKING.declare('revenue_threshold', ENTRIES['revenue'])\n"
            "    PACKING.declare('greedy_routing_heuristic', ENTRIES['supermodular_greedy'])"
        )
        if "revenue" in packing and "supermodular_greedy" in packing
        else "",
    )

    routing = scan(SRC / "policies" / "routing", "RoutingAlgorithmRegistry.register")
    routing.update(scan(SRC / "policies" / "packing_and_routing", "RoutingAlgorithmRegistry.register"))
    write_manifest(
        SRC / "policies" / "routing" / "_manifest.py",
        "logic.src.utils.registry",
        "ROUTING",
        routing,
    )

    improvement = scan(SRC / "policies" / "route_improvement", "RouteImproverRegistry.register")
    write_manifest(
        SRC / "policies" / "route_improvement" / "_manifest.py",
        "logic.src.utils.registry",
        "IMPROVEMENT",
        improvement,
        extra=(
            "    aliases = {\n"
            "        'ftsp': 'fast_tsp',\n"
            "        'tsp': 'fast_tsp',\n"
            "        'cls': 'classical_local_search',\n"
            "        'local_search': 'classical_local_search',\n"
            "        'rls': 'random_local_search',\n"
            "        'random': 'random_local_search',\n"
            "        'lkh3': 'lkh',\n"
            "        'lkh-3': 'lkh',\n"
            "        'lin_kernighan_helsgaun': 'lkh',\n"
            "        'dp': 'dp_route_reopt',\n"
            "    }\n"
            "    for alias, canonical in aliases.items():\n"
            "        if canonical in ENTRIES:\n"
            "            IMPROVEMENT.declare(alias, ENTRIES[canonical])"
        ),
    )

    acceptance = scan(SRC / "policies" / "acceptance_criteria", "AcceptanceCriterionRegistry.register")
    write_manifest(
        SRC / "policies" / "acceptance_criteria" / "_manifest.py",
        "logic.src.utils.registry",
        "ACCEPTANCE",
        acceptance,
    )

    joint = scan(SRC / "policies" / "packing_and_routing", "JointPolicyRegistry.register")
    write_manifest(
        SRC / "policies" / "packing_and_routing" / "_manifest.py",
        "logic.src.utils.registry",
        "JOINT",
        joint,
    )


if __name__ == "__main__":
    main()
